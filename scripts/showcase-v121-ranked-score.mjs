// Score design invariant: the Bounty board is bounded and independent of raw campaign
// points, paint erase/repaint loops, rebuilt structures and unbounded waiting.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const q={paintFraction:0,done:0,dmask:0,landWin:0,score:0,
  showcaseRunStats:{peakFlow:0,time:0}};
q.LM=Array.from({length:5},(_,id)=>({id}));
q.lmDone=o=>o.id<q.done;
q.hallDone=()=>q.done===5;
q.paintPct=()=>q.paintFraction;
const c=vm.createContext(q);
vm.runInContext(fs.readFileSync('src/showcase-ranked-score.js','utf8'),c);
const api=c.showcaseRankedScore;
assert.equal(api.MAX_SCORE,99500);
api.begin(true);
assert.equal(api.current().score,0,'ranked score starts from zero');
q.score=99999999;
assert.equal(api.current().score,0,'farming native score must not increase the board');
q.paintFraction=.4;
assert.equal(api.current().paint,8000);
q.paintFraction=0;q.score+=99999999;
assert.equal(api.current().paint,8000,'erasure cannot reverse finite coverage credit');
q.dmask=15;
assert.equal(api.current().districts,0,'districts cannot score before Hall');
q.done=5;q.showcaseRunStats.peakFlow=5;
let s=api.current();
assert.equal(s.landmarks,20000);
assert.equal(s.districts,10000);
assert.equal(s.flow,7500);
assert.equal(s.conquest,0,'no win points before an actual victory');
q.landWin=2;q.showcaseRunStats.time=120;
s=api.current();
assert.equal(s.speed,10000);
assert.equal(s.conquest,30000);
assert.equal(s.score,85500);
assert.ok(s.score<=99500,'score exceeds documented ceiling');
const terminal=api.finish();
q.paintFraction=1;q.score+=99999999;q.showcaseRunStats.time=0;
assert.equal(api.current().score,terminal.score,'terminal score must be immutable');
api.begin(false);
assert.equal(api.current().score,0,'free play never submits a positive board score');
q.paintFraction=1;q.done=5;q.dmask=15;q.showcaseRunStats.peakFlow=5;
q.landWin=2;q.showcaseRunStats.time=0;
api.begin(true);
assert.equal(api.current().score,99500,'legitimate mathematical upper bound');
api.begin(true);
q.showcaseRunStats.time=750;
assert.equal(api.current().speed,0,'no reward for infinite waiting');
assert.equal(api.current().score,87500);
api.begin(true);q.paintFraction=0;q.done=0;q.dmask=0;q.landWin=0;
q.showcaseRunStats.peakFlow=0;q.showcaseRunStats.time=0;
assert.equal(api.current().score,0,'new attempts must not inherit progress');
console.log('v1.21 finite ranked-score: PASS max 99500, raw-score/repaint immunity, Hall gating, win speed, freeze/replay');
